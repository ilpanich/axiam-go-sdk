// splitWords breaks an identifier into words on separators AND on case
// boundaries, so a schema name the spec writes in CamelCase gets the same
// initialism treatment as a snake_case operation name.
//
// Without the case split the surface is inconsistent with itself: the namespace
// scim_tokens becomes SCIMTokens (it has an underscore to split on) while the
// schema CreateScimTokenRequest stays Scim (it does not), and the SDK ends up
// with SCIMTokens().Create(CreateScimTokenRequest{}) — two spellings of one
// initialism in a single call.
func splitWords(s string) []string {
	var words []string
	var current strings.Builder
	flush := func() {
		if current.Len() > 0 {
			words = append(words, current.String())
			current.Reset()
		}
	}
	runes := []rune(s)
	for i, r := range runes {
		switch {
		case r == '_' || r == '-' || r == ' ' || r == '.':
			flush()
		case r >= 'A' && r <= 'Z':
			// A new word starts at an uppercase run's first letter, and at the
			// last letter of an uppercase run followed by a lowercase one
			// (so "HTTPServer" splits as HTTP + Server).
			if i > 0 {
				prev := runes[i-1]
				next := rune(0)
				if i+1 < len(runes) {
					next = runes[i+1]
				}
				prevUpper := prev >= 'A' && prev <= 'Z'
				nextLower := next >= 'a' && next <= 'z'
				if !prevUpper || (prevUpper && nextLower) {
					flush()
				}
			}
			current.WriteRune(r)
		default:
			current.WriteRune(r)
		}
	}
	flush()
	return words
}

func pascal(s string) string {
	parts := splitWords(s)
	var b strings.Builder
	for _, p := range parts {
		if up, ok := initialisms[strings.ToLower(p)]; ok {
			b.WriteString(up)
			continue
		}
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	out := b.String()
	if renamed, ok := renamedSchemas[out]; ok {
		return renamed
	}
	return out
}

func camel(s string) string {
	p := pascal(s)
	if p == "" {
		return p
	}
	// Leading initialism stays lowercase in full: orgID -> orgID, not oRGID.
	for i, r := range p {
		if i > 0 && r >= 'a' && r <= 'z' {
			if i == 1 {
				return strings.ToLower(p[:1]) + p[1:]
			}
			return strings.ToLower(p[:i-1]) + p[i-1:]
		}
	}
	return strings.ToLower(p)
}

// goDoc renders text as a Go doc comment at the given indent.
func goDoc(indent, name, text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var b strings.Builder
	first := true
	for _, para := range strings.Split(text, "\n\n") {
		if !first {
			b.WriteString(indent + "//\n")
		}
		for _, line := range wrap(strings.Join(strings.Fields(para), " "), 72-len(indent)) {
			prefix := ""
			if first && name != "" {
				prefix = name + " "
				name = ""
			}
			b.WriteString(indent + "// " + prefix + line + "\n")
			first = false
		}
		first = false
	}
	return b.String()
}

func wrap(text string, width int) []string {
	words := strings.Fields(text)
	if len(words) == 0 {
		return nil
	}
	var out []string
	line := ""
	for _, w := range words {
		if line != "" && len(line)+1+len(w) > width {
			out = append(out, line)
			line = w
		} else if line == "" {
			line = w
		} else {
			line += " " + w
		}
	}
	if line != "" {
		out = append(out, line)
	}
	return out
}

func sortedNames[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

