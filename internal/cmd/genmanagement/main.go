func build() (map[string]string, error) {
	files := map[string]string{
		"management_models.go":                 emitModels(),
		"management_api.go":                    emitAPI(),
		"management_surface_generated_test.go": emitTest(),
	}
	for _, ns := range reg.order {
		files["management_"+ns+".go"] = emitNamespace(ns, reg.Namespaces[ns])
	}

	formatted := make(map[string]string, len(files))
	for name, src := range files {
		out, err := format.Source([]byte(src))
		if err != nil {
			return nil, fmt.Errorf("gofmt rejected generated %s: %w", name, err)
		}
		formatted[name] = string(out)
	}
	return formatted, nil
}

func main() {
	check := flag.Bool("check", false, "verify the committed output is current instead of writing it")
	flag.Parse()

	wd, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	root = wd

	if err := load(); err != nil {
		fmt.Fprintf(os.Stderr, "could not read the registry or spec: %v\n", err)
		os.Exit(1)
	}

	files, err := build()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	if *check {
		var stale []string
		for _, name := range sortedNames(files) {
			existing, err := os.ReadFile(filepath.Join(root, name))
			if err != nil || string(existing) != files[name] {
				stale = append(stale, name)
			}
		}
		if len(stale) > 0 {
			for _, name := range stale {
				fmt.Fprintf(os.Stderr, "FAIL: %s is stale\n", name)
			}
			fmt.Fprintln(os.Stderr, "run `go run ./internal/cmd/genmanagement`")
			os.Exit(1)
		}
		fmt.Printf("OK: %d generated files are current (%d operations)\n", len(files), reg.OperationCount)
		return
	}

	for _, name := range sortedNames(files) {
		if err := os.WriteFile(filepath.Join(root, name), []byte(files[name]), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Printf("wrote %d files: %d operations across %d namespaces\n",
		len(files), reg.OperationCount, reg.NamespaceCount)
}
