// schemaNode is the subset of JSON Schema this surface actually uses.
type schemaNode struct {
	Ref         string                 `json:"$ref"`
	Type        any                    `json:"type"`
	Format      string                 `json:"format"`
	Enum        []any                  `json:"enum"`
	Items       *schemaNode            `json:"items"`
	Properties  map[string]*schemaNode `json:"properties"`
	Required    []string               `json:"required"`
	AllOf       []*schemaNode          `json:"allOf"`
	OneOf       []*schemaNode          `json:"oneOf"`
	AnyOf       []*schemaNode          `json:"anyOf"`
	Description string                 `json:"description"`

	propOrder []string
}

func parseSchema(raw json.RawMessage) *schemaNode {
	if len(raw) == 0 {
		return nil
	}
	var n schemaNode
	if err := json.Unmarshal(raw, &n); err != nil {
		return nil
	}
	var holder struct {
		Properties json.RawMessage `json:"properties"`
	}
	if err := json.Unmarshal(raw, &holder); err == nil && len(holder.Properties) > 0 {
		n.propOrder = orderedKeys(holder.Properties)
	}
	return &n
}

// propNames lists a node's property names.
//
// parseSchema records declaration order only for a schema read from the top
// level of components.schemas; a node reached as a nested allOf/oneOf member is
// decoded straight into schemaNode and has none. Falling back to the map's
// sorted keys is what stops those members' fields being silently DROPPED — the
// bug this helper exists to prevent lost provisioning_token from
// CreateScimTokenResponse, whose only field is declared in an inline allOf
// member, and a dropped field on a one-time secret is unrecoverable.
func propNames(n *schemaNode) []string {
	if n == nil {
		return nil
	}
	if len(n.propOrder) > 0 {
		return n.propOrder
	}
	return sortedNames(n.Properties)
}

func schemaByName(name string) *schemaNode {
	raw, ok := schemas[name]
	if !ok {
		return nil
	}
	return parseSchema(raw)
}

func refName(ref string) string {
	i := strings.LastIndex(ref, "/")
	return ref[i+1:]
}

func (n *schemaNode) typeName() string {
	switch t := n.Type.(type) {
	case string:
		return t
	case []any:
		for _, v := range t {
			if s, ok := v.(string); ok && s != "null" {
				return s
			}
		}
	}
	return ""
}

func (n *schemaNode) isNullable() bool {
	if t, ok := n.Type.([]any); ok {
		for _, v := range t {
			if s, ok := v.(string); ok && s == "null" {
				return true
			}
		}
	}
	return false
}

// nullableRef detects {oneOf: [{type: null}, {$ref: X}]} — utoipa's
// optional-enum shape.
func (n *schemaNode) nullableRef() string {
	if len(n.OneOf) != 2 {
		return ""
	}
	nulls, ref := 0, ""
	for _, v := range n.OneOf {
		if v.typeName() == "null" && v.Ref == "" {
			nulls++
		}
		if v.Ref != "" {
			ref = refName(v.Ref)
		}
	}
	if nulls == 1 && ref != "" {
		return ref
	}
	return ""
}

// goType is the Go type for a schema, without optionality applied.
func goType(n *schemaNode) string {
	if n == nil {
		return "any"
	}
	if n.Ref != "" {
		return pascal(refName(n.Ref))
	}
	if inner := n.nullableRef(); inner != "" {
		return "*" + pascal(inner)
	}
	if len(n.OneOf) > 0 || len(n.AnyOf) > 0 {
		return "any"
	}
	switch n.typeName() {
	case "string":
		if n.Format == "uuid" {
			return "uuid.UUID"
		}
		if len(n.Enum) > 0 {
			return "string"
		}
		return "string"
	case "integer":
		if n.Format == "int64" {
			return "int64"
		}
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + goType(n.Items)
	case "object":
		return "map[string]any"
	}
	return "any"
}

// flatten resolves allOf into one property set, preserving declaration order.
func flatten(name string) (props map[string]*schemaNode, order []string, required map[string]bool, desc string) {
	props = map[string]*schemaNode{}
	required = map[string]bool{}
	seen := map[string]bool{}

	var absorb func(n *schemaNode)
	absorb = func(n *schemaNode) {
		if n == nil {
			return
		}
		if n.Ref != "" {
			absorb(schemaByName(refName(n.Ref)))
			return
		}
		for _, p := range propNames(n) {
			if !seen[p] {
				seen[p] = true
				order = append(order, p)
			}
			props[p] = n.Properties[p]
		}
		for _, r := range n.Required {
			required[r] = true
		}
		for _, sub := range n.AllOf {
			absorb(sub)
		}
	}

	top := schemaByName(name)
	if top != nil {
		desc = top.Description
	}
	absorb(top)
	sort.Strings(order)
	return props, order, required, desc
}

// unionArm is one variant of an internally-tagged union.
type unionArm struct {
	Value string
	Props map[string]*schemaNode
	Order []string
	Req   map[string]bool
}

// discriminated detects an internally-tagged union and returns its tag and arms.
func discriminated(n *schemaNode) (string, []unionArm, bool) {
	if n == nil || len(n.OneOf) < 2 {
		return "", nil, false
	}
	tag := ""
	var arms []unionArm
	for _, variant := range n.OneOf {
		parts := variant.AllOf
		if len(parts) == 0 {
			parts = []*schemaNode{variant}
		}
		arm := unionArm{Props: map[string]*schemaNode{}, Req: map[string]bool{}}
		value := ""
		for _, part := range parts {
			if part.Ref != "" {
				p, order, req, _ := flatten(refName(part.Ref))
				for k, v := range p {
					arm.Props[k] = v
				}
				arm.Order = append(arm.Order, order...)
				for k := range req {
					arm.Req[k] = true
				}
				continue
			}
			for _, name := range propNames(part) {
				prop := part.Properties[name]
				if prop.typeName() == "string" && len(prop.Enum) == 1 {
					if s, ok := prop.Enum[0].(string); ok {
						if tag != "" && tag != name {
							return "", nil, false
						}
						tag, value = name, s
						continue
					}
				}
				arm.Props[name] = prop
				arm.Order = append(arm.Order, name)
				for _, r := range part.Required {
					if r == name {
						arm.Req[name] = true
					}
				}
			}
		}
		if value == "" {
			return "", nil, false
		}
		arm.Value = value
		arms = append(arms, arm)
	}
	return tag, arms, true
}

// sensitiveFields maps a schema name to the fields the registry marks secret.
func sensitiveFields() map[string]map[string]bool {
	out := map[string]map[string]bool{}
	add := func(schema string, fields []string) {
		if schema == "" || len(fields) == 0 {
			return
		}
		key := strings.TrimPrefix(schema, "[]")
		if out[key] == nil {
			out[key] = map[string]bool{}
		}
		for _, f := range fields {
			out[key][f] = true
		}
	}
	for _, ns := range reg.Namespaces {
		for _, op := range ns.Operations {
			add(op.RequestSchema, op.SensitiveRequestFields)
			add(op.Response.Schema, op.SensitiveResponseFields)
		}
	}
	return out
}

// replacementSchemas are the request bodies whose PUT replaces rather than
// patches (§27.4 rule 5). Read from the registry's update_style rather than
// inferred from "every field is required", which is also true of most response
// types and would scatter constructors across the whole model file.
func replacementSchemas() map[string]bool {
	out := map[string]bool{}
	for _, ns := range reg.Namespaces {
		for _, op := range ns.Operations {
			if op.UpdateStyle == "replace" && op.RequestSchema != "" {
				out[strings.TrimPrefix(op.RequestSchema, "[]")] = true
			}
		}
	}
	return out
}

// requestSchemas are the schemas that travel outbound, and so need a wire twin
// when they carry a secret.
func requestSchemas() map[string]bool {
	out := map[string]bool{}
	for _, ns := range reg.Namespaces {
		for _, op := range ns.Operations {
			if op.RequestSchema != "" {
				out[strings.TrimPrefix(op.RequestSchema, "[]")] = true
			}
		}
	}
	return out
}

// schemaClosure is every schema reachable from an operation, transitively.
func schemaClosure() []string {
	seeds := map[string]bool{}
	for _, ns := range reg.Namespaces {
		for _, op := range ns.Operations {
			if op.RequestSchema != "" {
				seeds[strings.TrimPrefix(op.RequestSchema, "[]")] = true
			}
			if op.Response.Schema != "" {
				seeds[strings.TrimPrefix(op.Response.Schema, "[]")] = true
			}
		}
	}

	var refsIn func(raw json.RawMessage, found map[string]bool)
	refsIn = func(raw json.RawMessage, found map[string]bool) {
		var node any
		if err := json.Unmarshal(raw, &node); err != nil {
			return
		}
		var walk func(v any)
		walk = func(v any) {
			switch t := v.(type) {
			case map[string]any:
				for k, val := range t {
					if k == "$ref" {
						if s, ok := val.(string); ok {
							found[refName(s)] = true
						}
						continue
					}
					walk(val)
				}
			case []any:
				for _, item := range t {
					walk(item)
				}
			}
		}
		walk(node)
	}

	seen := map[string]bool{}
	frontier := sortedNames(seeds)
	for len(frontier) > 0 {
		name := frontier[len(frontier)-1]
		frontier = frontier[:len(frontier)-1]
		if seen[name] {
			continue
		}
		raw, ok := schemas[name]
		if !ok {
			continue
		}
		seen[name] = true
		found := map[string]bool{}
		refsIn(raw, found)
		for _, f := range sortedNames(found) {
			if !seen[f] {
				frontier = append(frontier, f)
			}
		}
	}
	return sortedNames(seen)
}

