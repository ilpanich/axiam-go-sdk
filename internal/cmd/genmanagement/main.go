type param struct {
	Name     string `json:"name"`
	Format   string `json:"format"`
	Required bool   `json:"required"`
	// Type is `any` because the registry writes a nullable query parameter's
	// type as the array ["string","null"] rather than a bare string. It is not
	// read — every query parameter on this surface travels as a string — but
	// decoding must not fail on the shape.
	Type any `json:"type"`
}

type response struct {
	Status int    `json:"status"`
	Kind   string `json:"kind"`
	Schema string `json:"schema"`
}

type operation struct {
	Method                  string   `json:"method"`
	Path                    string   `json:"path"`
	PathParams              []param  `json:"path_params"`
	QueryParams             []param  `json:"query_params"`
	Paginated               bool     `json:"paginated"`
	RequestBody             string   `json:"request_body"`
	RequestSchema           string   `json:"request_schema"`
	Response                response `json:"response"`
	SensitiveResponseFields []string `json:"sensitive_response_fields"`
	SensitiveRequestFields  []string `json:"sensitive_request_fields"`
	UpdateStyle             string   `json:"update_style"`
	Summary                 string   `json:"summary"`
}

type namespace struct {
	Doc        string               `json:"doc"`
	Operations map[string]operation `json:"operations"`
	order      []string
}

type registry struct {
	SpecVersion    string               `json:"spec_version"`
	OperationCount int                  `json:"operation_count"`
	NamespaceCount int                  `json:"namespace_count"`
	Namespaces     map[string]namespace `json:"namespaces"`
	order          []string
}

