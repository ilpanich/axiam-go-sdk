// Command genmanagement generates the CONTRACT §27 management surface.
//
// It reads management-registry.json (the 146 operations across 24 namespaces,
// maintained in ilpanich/axiam and vendored here) plus openapi.json for the
// schemas those operations carry, and writes:
//
//   - management_models.go        — every request and response type
//   - management_<namespace>.go   — one namespace handle per namespace
//   - management_api.go           — the accessors on *Client
//   - management_surface_generated_test.go — one conformance case per operation
//
// Run with -check to verify the committed output is current; that is what CI
// runs, so a registry change that is not regenerated fails the build rather
// than shipping a surface that disagrees with the contract.
//
// Layout is decided by go/format rather than by this program's line breaking,
// the same way gofmt decides it for hand-written code.
//
//	go run ./internal/cmd/genmanagement
//	go run ./internal/cmd/genmanagement -check
