	b.WriteString(goDoc("", "generatedSurface", "is every operation the cases above reach."))
	b.WriteString("var generatedSurface = []string{\n")
	for _, name := range all {
		b.WriteString(fmt.Sprintf("\t%q,\n", name))
	}
	b.WriteString("}\n\n")
	// §27.5 conformance, generated from the registry's own sensitive-field
	// lists. This exists because a generator that silently drops a field is a
	// class of bug the path-and-status conformance cases above cannot see: the
	// call still reaches the right route, and the secret simply is not there.
	type secretCase struct{ schema, field string }
	var secretCases []secretCase
	seenSecret := map[string]bool{}
	for _, ns := range reg.order {
		def := reg.Namespaces[ns]
		for _, opName := range def.order {
			op := def.Operations[opName]
			for _, pair := range []struct {
				schema string
				fields []string
			}{
				{op.Response.Schema, op.SensitiveResponseFields},
				{op.RequestSchema, op.SensitiveRequestFields},
			} {
				if pair.schema == "" {
					continue
				}
				for _, f := range pair.fields {
					key := pair.schema + "." + f
					if seenSecret[key] {
						continue
					}
					seenSecret[key] = true
					secretCases = append(secretCases, secretCase{strings.TrimPrefix(pair.schema, "[]"), f})
				}
			}
		}
	}
	sort.Slice(secretCases, func(i, j int) bool {
		if secretCases[i].schema != secretCases[j].schema {
			return secretCases[i].schema < secretCases[j].schema
		}
		return secretCases[i].field < secretCases[j].field
	})

	b.WriteString(goDoc("", "TestGeneratedSecretFieldsAreSensitive",
		"is §27.5: every field the registry marks secret exists on its model and is a "+
			"Sensitive.\n\nA generated model that silently dropped one would still pass every "+
			"path-and-status case above — the call reaches the right route and the secret is "+
			"simply absent — which is exactly how a one-time credential goes missing."))
	b.WriteString("func TestGeneratedSecretFieldsAreSensitive(t *testing.T) {\n")
