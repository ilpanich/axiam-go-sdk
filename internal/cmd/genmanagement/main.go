const modelsHeader = `// Request and response types for the CONTRACT §27 management surface.
//
// Three shapes recur and are worth knowing before reading:
//
//   - Sparse update bodies. Every field is a pointer with omitempty, so a field
//     you leave nil is ABSENT from the wire body rather than sent as null — a
//     body carrying one field changes one field (§27.4 rule 5).
//   - Replacement bodies. SetOrgSettings, the organization email config,
//     WebauthnAttestationPolicy and SetMtlsTrustAnchor have required fields,
//     because a PUT on those routes replaces rather than patches. Each has a
//     New… constructor taking every required field, so "I forgot one" is a
//     compile error at the call site rather than a silent zero value.
//   - Types carrying a secret. These hold a Sensitive, whose MarshalJSON emits
//     "[SENSITIVE]" — so a request type carrying one also has an unexported
//     wire twin and a toWire method. That is the single place a §27 secret is
//     unwrapped for the socket (§7 rule 4).

`

func emitModels() string {
	secrets := sensitiveFields()
	outbound := requestSchemas()
	replacements := replacementSchemas()
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString(modelsHeader)
	b.WriteString("package axiam\n\nimport (\n\t\"github.com/google/uuid\"\n)\n\n")

	for _, name := range schemaClosure() {
		node := schemaByName(name)
		if node == nil {
			continue
		}
		typeName := pascal(name)

		if len(node.Enum) > 0 && node.typeName() == "string" {
			emitEnum(&b, typeName, node)
			continue
		}
		if tag, arms, ok := discriminated(node); ok {
			emitUnion(&b, typeName, node, tag, arms)
			continue
		}
		emitStruct(&b, typeName, name, secrets[name], outbound[name], replacements[name])
	}
	return b.String()
}

func emitEnum(b *strings.Builder, typeName string, node *schemaNode) {
	desc := node.Description
	if desc == "" {
		desc = fmt.Sprintf("is a %s value from the server's schema.", typeName)
	} else {
		desc = lowerFirstSentence(desc)
	}
	b.WriteString(goDoc("", typeName, desc))
	b.WriteString(fmt.Sprintf("type %s string\n\n", typeName))
	b.WriteString(fmt.Sprintf("// The %s values the server defines.\nconst (\n", typeName))
	for _, v := range node.Enum {
		s, ok := v.(string)
		if !ok {
			continue
		}
		b.WriteString(fmt.Sprintf("\t%s%s %s = %q\n", typeName, pascal(s), typeName, s))
	}
	b.WriteString(")\n\n")
}

// emitUnion renders an internally-tagged union as one struct.
//
// Go has no sum type, so the honest rendering is the tag plus every arm's
// fields as pointers, documented with which are present for which tag value. An
// interface would force a type switch on a shape the server describes with one
// string, and would not round-trip through encoding/json without a hand-written
// UnmarshalJSON per union.
func emitUnion(b *strings.Builder, typeName string, node *schemaNode, tag string, arms []unionArm) {
	desc := node.Description
	if desc == "" {
		desc = fmt.Sprintf("is a union discriminated by %s.", tag)
	} else {
		desc = lowerFirstSentence(desc)
	}
	var which []string
	merged := map[string]*schemaNode{}
	var order []string
	seen := map[string]bool{}
	for _, arm := range arms {
		var present []string
		for _, f := range arm.Order {
			if !seen[f] {
				seen[f] = true
				order = append(order, f)
			}
			merged[f] = arm.Props[f]
			present = append(present, f)
		}
		sort.Strings(present)
		if len(present) == 0 {
			which = append(which, fmt.Sprintf("%s=%q carries no further fields.", tag, arm.Value))
		} else {
			which = append(which, fmt.Sprintf("%s=%q carries %s.", tag, arm.Value, strings.Join(present, ", ")))
		}
	}
	sort.Strings(order)

	desc += "\n\nGo has no sum type, so every arm's fields live on this one struct as " +
		"pointers and " + tag + " says which are set: " + strings.Join(which, " ") +
		" A field belonging to another arm is nil."
	b.WriteString(goDoc("", typeName, desc))
	b.WriteString(fmt.Sprintf("type %s struct {\n", typeName))
	b.WriteString(goDoc("\t", pascal(tag), "is the discriminator: it says which of the fields below are set."))
	b.WriteString(fmt.Sprintf("\t%s string `json:%q`\n", pascal(tag), tag))
	for _, f := range order {
		emitField(b, f, merged[f], false, false)
	}
	b.WriteString("}\n\n")
}

func lowerFirstSentence(s string) string {
	s = strings.TrimSpace(strings.ReplaceAll(s, "\n", " "))
	if s == "" {
		return s
	}
	return s
}

func emitField(b *strings.Builder, name string, node *schemaNode, required, secret bool) {
	goName := pascal(name)
	typ := goType(node)
	if secret {
		typ = "Sensitive"
	}
	tag := name
	if !required {
		if !strings.HasPrefix(typ, "*") && !strings.HasPrefix(typ, "[]") && !strings.HasPrefix(typ, "map[") {
			typ = "*" + typ
		}
		tag += ",omitempty"
	}
	desc := ""
	if node != nil {
		desc = node.Description
	}
	if desc == "" {
		desc = fmt.Sprintf("carries the server's %s field.", name)
	} else {
		desc = lowerFirstSentence(desc)
	}
	if secret {
		desc += "\n\nSecret. Redacted from every fmt verb, log line and JSON rendering; " +
			"the raw value never leaves this package except on the wire."
	}
	b.WriteString(goDoc("\t", goName, desc))
	b.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", goName, typ, tag))
}

func emitStruct(b *strings.Builder, typeName, schemaName string, secrets map[string]bool, outbound, replacement bool) {
	props, order, required, desc := flatten(schemaName)
	if desc == "" {
		desc = fmt.Sprintf("is the %s schema from the server's OpenAPI document.", typeName)
	} else {
		desc = lowerFirstSentence(desc)
	}
	allOptional := len(order) > 0 && len(required) == 0
	if allOptional {
		desc += "\n\nEvery field is optional, so this is a SPARSE body: what you leave nil " +
			"is left unchanged, and is omitted from the wire request entirely rather than " +
			"sent as null (§27.4 rule 5)."
	}

	b.WriteString(goDoc("", typeName, desc))
	b.WriteString(fmt.Sprintf("type %s struct {\n", typeName))
	if len(order) == 0 {
		b.WriteString("\t// The server documents no fields on this schema.\n")
	}
	for _, f := range order {
		emitField(b, f, props[f], required[f], secrets[f])
	}
	b.WriteString("}\n\n")

	// A replacement body gets a constructor naming every required field.
	//
	// §27.9 asks that a replacement type "does not compile with a field
	// omitted". Go cannot express that on a struct — a keyed literal may always
	// leave fields at their zero value — so the strongest available guarantee is
	// a constructor that takes every one of them: forgetting a field is then a
	// compile error at the call site, and the documented way to build the body
	// is the way that cannot be half-filled.
	if replacement && len(order) > 0 {
		emitConstructor(b, typeName, props, order, required, secrets)
	}

	if len(secrets) > 0 && outbound {
		emitWireTwin(b, typeName, props, order, required, secrets)
	}
}

func emitConstructor(b *strings.Builder, typeName string, props map[string]*schemaNode, order []string, required map[string]bool, secrets map[string]bool) {
	var args, assigns []string
	var optional []string
	for _, f := range order {
		if !required[f] {
			optional = append(optional, pascal(f))
			continue
		}
		typ := goType(props[f])
		if secrets[f] {
			typ = "Sensitive"
		}
		args = append(args, fmt.Sprintf("%s %s", camel(f), typ))
		assigns = append(assigns, fmt.Sprintf("%s: %s", pascal(f), camel(f)))
	}
	if len(args) == 0 {
		return
	}
	doc := fmt.Sprintf(
		"builds a %s with every field the server requires.\n\nThis body REPLACES rather "+
			"than patches (§27.4 rule 5), so what you do not carry over from a prior read is "+
			"not preserved — it is overwritten. Taking every required field as an argument is "+
			"what makes forgetting one a compile error rather than a silent zero value on the "+
			"wire.", typeName)
	if len(optional) > 0 {
		doc += fmt.Sprintf("\n\nThe optional fields (%s) stay settable on the returned value, "+
			"and are equally overwritten when omitted — read the current state first and carry "+
			"them across.", strings.Join(optional, ", "))
	}
	b.WriteString(goDoc("", "New"+typeName, doc))
	b.WriteString(fmt.Sprintf("func New%s(%s) %s {\n\treturn %s{%s}\n}\n\n",
		typeName, strings.Join(args, ", "), typeName, typeName, strings.Join(assigns, ", ")))
}

func emitWireTwin(b *strings.Builder, typeName string, props map[string]*schemaNode, order []string, required map[string]bool, secrets map[string]bool) {
	wire := camel(typeName) + "Wire"
	b.WriteString(fmt.Sprintf(
		"// %s is the outbound twin of %s: plain strings where the public type\n"+
			"// holds a Sensitive.\n//\n"+
			"// It exists because Sensitive.MarshalJSON emits \"[SENSITIVE]\" — marshalling\n"+
			"// the public type directly would send the placeholder to the server.\n",
		wire, typeName))
	b.WriteString(fmt.Sprintf("type %s struct {\n", wire))
	for _, f := range order {
		typ := goType(props[f])
		if secrets[f] {
			typ = "string"
		}
		tag := f
		if !required[f] {
			if !strings.HasPrefix(typ, "*") && !strings.HasPrefix(typ, "[]") && !strings.HasPrefix(typ, "map[") {
				typ = "*" + typ
			}
			tag += ",omitempty"
		}
		b.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", pascal(f), typ, tag))
	}
	b.WriteString("}\n\n")

	b.WriteString(fmt.Sprintf(
		"// toWire unwraps the secret fields of a %s for the socket.\n//\n"+
			"// One of the few places a §27 secret is unwrapped, so \"put a secret on the\n"+
			"// wire\" stays a greppable call rather than fourteen (§7 rule 4).\n",
		typeName))
	b.WriteString(fmt.Sprintf("func (v %s) toWire() %s {\n\treturn %s{\n", typeName, wire, wire))
	for _, f := range order {
		if secrets[f] {
			if required[f] {
				b.WriteString(fmt.Sprintf("\t\t%s: v.%s.expose(),\n", pascal(f), pascal(f)))
			} else {
				b.WriteString(fmt.Sprintf("\t\t%s: exposeOptional(v.%s),\n", pascal(f), pascal(f)))
			}
			continue
		}
		b.WriteString(fmt.Sprintf("\t\t%s: v.%s,\n", pascal(f), pascal(f)))
	}
	b.WriteString("\t}\n}\n\n")
}

