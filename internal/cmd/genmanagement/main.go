// orderedKeys reads the key order of a JSON object as it appears in the file,
// so generated output follows the registry's own order rather than Go's
// randomised map iteration — which would make every regeneration a diff.
func orderedKeys(raw []byte) []string {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if _, err := dec.Token(); err != nil { // opening brace
		return nil
	}
	var keys []string
	depth := 0
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return keys
		}
		if depth == 0 {
			keys = append(keys, tok.(string))
			var skip json.RawMessage
			if err := dec.Decode(&skip); err != nil {
				return keys
			}
		}
	}
	return keys
}

func load() error {
	regRaw, err := os.ReadFile(filepath.Join(root, "management-registry.json"))
	if err != nil {
		return err
	}
	if err := json.Unmarshal(regRaw, &reg); err != nil {
		return err
	}

	var regObj struct {
		Namespaces json.RawMessage `json:"namespaces"`
	}
	if err := json.Unmarshal(regRaw, &regObj); err != nil {
		return err
	}
	reg.order = orderedKeys(regObj.Namespaces)

	var nsRaw map[string]json.RawMessage
	if err := json.Unmarshal(regObj.Namespaces, &nsRaw); err != nil {
		return err
	}
	for name, raw := range nsRaw {
		var holder struct {
			Operations json.RawMessage `json:"operations"`
		}
		if err := json.Unmarshal(raw, &holder); err != nil {
			return err
		}
		ns := reg.Namespaces[name]
		ns.order = orderedKeys(holder.Operations)
		reg.Namespaces[name] = ns
	}

	specRaw, err := os.ReadFile(filepath.Join(root, "openapi.json"))
	if err != nil {
		return err
	}
	var spec struct {
		Components struct {
			Schemas map[string]json.RawMessage `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(specRaw, &spec); err != nil {
		return err
	}
	schemas = spec.Components.Schemas
	return nil
}

