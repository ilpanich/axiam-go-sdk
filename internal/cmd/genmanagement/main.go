// implicitParams reports which of an operation's path params default from the
// client (§27.4 rule 3).
func implicitParams(ns string, op operation) map[string]bool {
	out := map[string]bool{}
	for _, p := range op.PathParams {
		if p.Name == "org_id" {
			out["org_id"] = true
		}
		if p.Name == "tenant_id" && implicitTenantNamespaces[ns] {
			out["tenant_id"] = true
		}
	}
	return out
}

func splitQuery(op operation) (req, opt []param) {
	for _, q := range op.QueryParams {
		if q.Name == "offset" || q.Name == "limit" {
			continue
		}
		if q.Required {
			req = append(req, q)
		} else {
			opt = append(opt, q)
		}
	}
	return req, opt
}

func filterTypeName(ns, opName string, opt []param) string {
	if len(opt) <= 2 {
		return ""
	}
	return pascal(ns) + pascal(opName) + "Filter"
}

// arg is one caller-facing parameter of a generated method.
type arg struct {
	name string
	typ  string
}

func operationArgs(ns, opName string, op operation) []arg {
	implicit := implicitParams(ns, op)
	var args []arg
	for _, p := range op.PathParams {
		if implicit[p.Name] {
			continue
		}
		typ := "string"
		if p.Format == "uuid" {
			typ = "uuid.UUID"
		}
		args = append(args, arg{camel(p.Name), typ})
	}
	reqQ, optQ := splitQuery(op)
	for _, q := range reqQ {
		args = append(args, arg{camel(q.Name), "string"})
	}
	if op.RequestBody == "schema" {
		args = append(args, arg{"body", pascal(op.RequestSchema)})
	} else if op.RequestBody == "untyped" {
		args = append(args, arg{"body", "any"})
	}
	if f := filterTypeName(ns, opName, optQ); f != "" {
		args = append(args, arg{"filter", f})
	} else {
		for _, q := range optQ {
			args = append(args, arg{camel(q.Name), "string"})
		}
	}
	if op.Paginated {
		args = append(args, arg{"page", "PageRequest"})
	}
	return args
}

func responseType(op operation) string {
	switch op.Response.Kind {
	case "none":
		return ""
	case "array":
		return "[]" + pascal(op.Response.Schema)
	case "page":
		return "Page[" + pascal(op.Response.Schema) + "]"
	}
	return pascal(op.Response.Schema)
}

func operationDoc(method, canonical string, op operation) string {
	text := fmt.Sprintf("issues %s %s.", op.Method, op.Path)
	if op.UpdateStyle == "replace" {
		text += "\n\nThis is a REPLACEMENT, not a patch (§27.4 rule 5). Every field of the " +
			"body is required, and what you do not carry over from a prior read is not " +
			"preserved — it is overwritten. Read first, change the field you mean, send the " +
			"whole thing back."
	}
	if len(op.SensitiveResponseFields) > 0 {
		text += fmt.Sprintf("\n\nReturns secret material, once. %s is returned by this call "+
			"and by no other; no later Get will return it again, and the Get projection has "+
			"no field where it was. Discarding the result destroys the credential "+
			"(§27.5 rule 3).", strings.Join(op.SensitiveResponseFields, ", "))
	}
	if op.Method != "GET" {
		text += "\n\nNot retried on failure (§27.4 rule 8): every write on this surface is " +
			"issued exactly once, including the ones that look idempotent."
	}
	return text
}

func emitNamespace(ns string, def namespace) string {
	handle := pascal(ns) + "API"
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString(goDoc("", "", fmt.Sprintf("The %s management namespace (CONTRACT §27.1).\n\n%s", ns, def.Doc)))
	b.WriteString("\npackage axiam\n\n")

	var body strings.Builder

	// Filter structs for operations with more than two optional filters.
	for _, opName := range def.order {
		op := def.Operations[opName]
		_, optQ := splitQuery(op)
		name := filterTypeName(ns, opName, optQ)
		if name == "" {
			continue
		}
		body.WriteString(goDoc("", name, fmt.Sprintf(
			"holds the optional filters for %s.%s.\n\nSix loose optional string arguments "+
				"is a call site a reader cannot check and a refactor silently reorders, so "+
				"they travel as one struct. A zero field is not sent.", ns, opName)))
		body.WriteString(fmt.Sprintf("type %s struct {\n", name))
		for _, q := range optQ {
			body.WriteString(goDoc("\t", pascal(q.Name), fmt.Sprintf("filters on %s. Empty means unset.", q.Name)))
			body.WriteString(fmt.Sprintf("\t%s string\n", pascal(q.Name)))
		}
		body.WriteString("}\n\n")
	}

	hasOrg, hasTenant := false, false
	for _, opName := range def.order {
		implicit := implicitParams(ns, def.Operations[opName])
		hasOrg = hasOrg || implicit["org_id"]
		hasTenant = hasTenant || implicit["tenant_id"]
	}

	body.WriteString(goDoc("", handle, fmt.Sprintf(
		"is the %s namespace handle.\n\n%s\n\nAcquiring one performs no I/O and allocates "+
			"nothing meaningful (§27.2 rule 1); it holds the client and cannot be "+
			"constructed without one.", ns, def.Doc)))
	body.WriteString(fmt.Sprintf("type %s struct {\n\tc *Client\n\tscope namespaceScope\n}\n\n", handle))

	if hasOrg {
		body.WriteString(goDoc("", "InOrg", fmt.Sprintf(
			"addresses a different organization than the client's own.\n\n§27.4 rule 3: the "+
				"client's organization is the default, and a platform-admin token legitimately "+
				"overrides it. Returns a new handle; the original is unchanged.")))
		body.WriteString(fmt.Sprintf(
			"func (a *%s) InOrg(orgID uuid.UUID) *%s {\n\treturn &%s{c: a.c, scope: a.scope.withOrg(orgID)}\n}\n\n",
			handle, handle, handle))
	}
	if hasTenant {
		body.WriteString(goDoc("", "ForTenant",
			"addresses a different tenant than the client's own (§27.4 rule 3).\n\nReturns a new handle; the original is unchanged."))
		body.WriteString(fmt.Sprintf(
			"func (a *%s) ForTenant(tenantID uuid.UUID) *%s {\n\treturn &%s{c: a.c, scope: a.scope.withTenant(tenantID)}\n}\n\n",
			handle, handle, handle))
	}

	for _, opName := range def.order {
		emitOperation(&body, ns, opName, def.Operations[opName], handle)
	}

	rendered := body.String()
	// Imports are derived from what was actually rendered rather than assumed,
	// so a namespace with no paths to format does not import fmt and trip the
	// unused-import compile error.
	var std []string
	std = append(std, "\"context\"")
	if strings.Contains(rendered, "fmt.Sprintf") {
		std = append(std, "\"fmt\"")
	}
	if strings.Contains(rendered, "http.Method") {
		std = append(std, "\"net/http\"")
	}
	if strings.Contains(rendered, "url.Values") || strings.Contains(rendered, "url.PathEscape") {
		std = append(std, "\"net/url\"")
	}
	sort.Strings(std)
	imports := std
	if strings.Contains(rendered, "uuid.UUID") {
		imports = append(imports, "", "\"github.com/google/uuid\"")
	}
	b.WriteString("import (\n")
	for _, imp := range imports {
		if imp == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString("\t" + imp + "\n")
	}
	b.WriteString(")\n\n")
	b.WriteString(rendered)
	return b.String()
}

func emitOperation(b *strings.Builder, ns, opName string, op operation, handle string) {
	canonical := ns + "." + opName
	method := pascal(opName)
	implicit := implicitParams(ns, op)
	args := operationArgs(ns, opName, op)

	var sig []string
	sig = append(sig, "ctx context.Context")
	for _, a := range args {
		sig = append(sig, a.name+" "+a.typ)
	}

	ret := responseType(op)
	retSig := "error"
	if ret != "" {
		retSig = "(" + ret + ", error)"
	}

	// The call builder, shared by the operation and (where paginated) its
	// ListAll walker, so the path, query and body are decided in one place.
	builder := fmt.Sprintf("call%s%s", pascal(ns), method)
	// A builder can only fail where it has to resolve an implicit {org_id} or
	// {tenant_id} from the client. Everywhere else it is total, and giving it an
	// error return anyway would put an unreachable branch in every one of the
	// 146 operations — dead code that no test can honestly cover.
	fallible := len(implicit) > 0
	var pre strings.Builder
	route := op.Path
	fmtArgs := []string{}
	for _, p := range op.PathParams {
		if implicit[p.Name] {
			fn := "resolveOrg"
			if p.Name == "tenant_id" {
				fn = "resolveTenant"
			}
			pre.WriteString(fmt.Sprintf("\t%s, err := a.c.%s(a.scope, %q)\n\tif err != nil {\n\t\treturn managementCall{}, err\n\t}\n",
				camel(p.Name), fn, canonical))
			route = strings.ReplaceAll(route, "{"+p.Name+"}", "%s")
			fmtArgs = append(fmtArgs, camel(p.Name)+".String()")
			continue
		}
		route = strings.ReplaceAll(route, "{"+p.Name+"}", "%s")
		if p.Format == "uuid" {
			fmtArgs = append(fmtArgs, camel(p.Name)+".String()")
		} else {
			fmtArgs = append(fmtArgs, "url.PathEscape("+camel(p.Name)+")")
		}
	}

	reqQ, optQ := splitQuery(op)
	filter := filterTypeName(ns, opName, optQ)
	var q strings.Builder
	if op.Paginated || len(reqQ) > 0 || len(optQ) > 0 {
		q.WriteString("\tquery := url.Values{}\n")
		for _, p := range reqQ {
			q.WriteString(fmt.Sprintf("\tquery.Set(%q, %s)\n", p.Name, camel(p.Name)))
		}
		for _, p := range optQ {
			src := camel(p.Name)
			if filter != "" {
				src = "filter." + pascal(p.Name)
			}
			q.WriteString(fmt.Sprintf("\tif %s != \"\" {\n\t\tquery.Set(%q, %s)\n\t}\n", src, p.Name, src))
		}
		if op.Paginated {
			q.WriteString("\tquery = pageQuery(page, query)\n")
		}
	}

	bodyExpr := "nil"
	if op.RequestBody == "schema" {
		if hasSecretRequest(op.RequestSchema) {
			bodyExpr = "body.toWire()"
		} else {
			bodyExpr = "body"
		}
	} else if op.RequestBody == "untyped" {
		bodyExpr = "body"
	}

	// Builder signature mirrors the operation's, minus ctx.
	var bsig []string
	for _, a := range args {
		bsig = append(bsig, a.name+" "+a.typ)
	}
	b.WriteString(fmt.Sprintf("// %s builds the %s call. Shared by the operation and its\n// auto-paging form, so the path, query and body are decided in one place.\n",
		builder, canonical))
	builderRet := "managementCall"
	if fallible {
		builderRet = "(managementCall, error)"
	}
	b.WriteString(fmt.Sprintf("func (a *%s) %s(%s) %s {\n", handle, builder, strings.Join(bsig, ", "), builderRet))
	b.WriteString(pre.String())
	b.WriteString(q.String())
	pathExpr := fmt.Sprintf("%q", route)
	if len(fmtArgs) > 0 {
		pathExpr = fmt.Sprintf("fmt.Sprintf(%q, %s)", route, strings.Join(fmtArgs, ", "))
	}
	b.WriteString("\treturn managementCall{\n")
	b.WriteString(fmt.Sprintf("\t\toperation:    %q,\n", canonical))
	b.WriteString(fmt.Sprintf("\t\tmethod:       %s,\n", httpMethodConst(op.Method)))
	b.WriteString(fmt.Sprintf("\t\tpathTemplate: %q,\n", op.Path))
	b.WriteString(fmt.Sprintf("\t\tpath:         %s,\n", pathExpr))
	if q.Len() > 0 {
		b.WriteString("\t\tquery:        query,\n")
	}
	if bodyExpr != "nil" {
		b.WriteString(fmt.Sprintf("\t\tbody:         %s,\n", bodyExpr))
	}
	if fallible {
		b.WriteString("\t}, nil\n}\n\n")
	} else {
		b.WriteString("\t}\n}\n\n")
	}

	// The operation itself.
	b.WriteString(goDoc("", method, operationDoc(method, canonical, op)))
	b.WriteString(fmt.Sprintf("func (a *%s) %s(%s) %s {\n", handle, method, strings.Join(sig, ", "), retSig))
	var fwd []string
	for _, a := range args {
		fwd = append(fwd, a.name)
	}
	if fallible {
		failure := "return err"
		if ret != "" {
			failure = fmt.Sprintf("var zero %s\n\t\treturn zero, err", ret)
		}
		b.WriteString(fmt.Sprintf("\tcall, err := a.%s(%s)\n\tif err != nil {\n\t\t%s\n\t}\n",
			builder, strings.Join(fwd, ", "), failure))
	} else {
		b.WriteString(fmt.Sprintf("\tcall := a.%s(%s)\n", builder, strings.Join(fwd, ", ")))
	}
	if ret == "" {
		b.WriteString("\treturn sendManagementNoContent(ctx, a.c, call)\n}\n\n")
	} else {
		b.WriteString(fmt.Sprintf("\treturn sendManagement[%s](ctx, a.c, call)\n}\n\n", ret))
	}

	if op.Paginated {
		inner := strings.TrimSuffix(strings.TrimPrefix(ret, "Page["), "]")
		var lead []arg
		for _, a := range args {
			if a.name != "page" {
				lead = append(lead, a)
			}
		}
		var leadSig []string
		var leadFwd []string
		leadSig = append(leadSig, "ctx context.Context")
		for _, a := range lead {
			leadSig = append(leadSig, a.name+" "+a.typ)
			leadFwd = append(leadFwd, a.name)
		}
		leadSig = append(leadSig, "start PageRequest")
		b.WriteString(goDoc("", method+"All", fmt.Sprintf(
			"walks %s to exhaustion, concatenating every page.\n\nThe auto-paging form §27.4 "+
				"rule 4 requires. It stops on an empty page even if Total disagrees, so a "+
				"misreporting server costs one wasted request rather than an unbounded loop.",
			canonical)))
		b.WriteString(fmt.Sprintf("func (a *%s) %sAll(%s) ([]%s, error) {\n", handle, method, strings.Join(leadSig, ", "), inner))
		callFwd := append(append([]string{"ctx"}, leadFwd...), "p")
		b.WriteString(fmt.Sprintf(
			"\treturn collectPages(ctx, start, func(ctx context.Context, p PageRequest) (Page[%s], error) {\n\t\treturn a.%s(%s)\n\t})\n}\n\n",
			inner, method, strings.Join(callFwd, ", ")))
	}
}

func httpMethodConst(m string) string {
	switch m {
	case "GET":
		return "http.MethodGet"
	case "POST":
		return "http.MethodPost"
	case "PUT":
		return "http.MethodPut"
	case "DELETE":
		return "http.MethodDelete"
	}
	return fmt.Sprintf("%q", m)
}

func hasSecretRequest(schema string) bool {
	if schema == "" {
		return false
	}
	return len(sensitiveFields()[strings.TrimPrefix(schema, "[]")]) > 0
}

